// Generates responsive, content-hashed WebP variants of the letter-world photography and a
// typed manifest the components read. Run after replacing any source image:
//   pnpm --filter @anonletter/web images
// Hashed names mean the variants can be cached forever (see public/_headers).
import { createHash } from "node:crypto";
import { mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = path.dirname(fileURLToPath(import.meta.url));
const SRC = path.resolve(root, "../public/assets/letter-world");
const OUT = path.join(SRC, "sized");
const MANIFEST = path.resolve(root, "../src/lib/imageManifest.ts");
const PUBLIC_PREFIX = "/assets/letter-world/sized";
const INDEX_HTML = path.resolve(root, "../index.html");
// The hero envelope is the LCP image; its preload must name the same variants the <img> picks.
const LCP = {
  name: "envelope-rose",
  sizes: "(max-width: 360px) 410px, (max-width: 760px) 460px, (max-width: 1100px) 500px, 620px",
};

// Widths cover phone/tablet/desktop at 1x–3x for each image's largest CSS size.
const MOOD_WIDTHS = [300, 450, 600, 800, 1000];
const IMAGES = {
  "envelope-rose": [480, 720, 960, 1200],
  "envelope-open": [480, 720, 960, 1200],
  "letter-paper": [400, 600, 800, 1000],
  "flower-stem": [260, 400, 520, 650],
  "soft-bloom": MOOD_WIDTHS,
  "old-letter": MOOD_WIDTHS,
  "night-thought": MOOD_WIDTHS,
  "quiet-garden": MOOD_WIDTHS,
  "confetti-love": MOOD_WIDTHS,
};

await rm(OUT, { recursive: true, force: true });
await mkdir(OUT, { recursive: true });

const manifest = {};
for (const [name, widths] of Object.entries(IMAGES)) {
  const input = path.join(SRC, `${name}.webp`);
  const meta = await sharp(input).metadata();
  const variants = [];
  for (const width of widths.filter((w) => w <= meta.width)) {
    const buffer = await sharp(input)
      .resize({ width, withoutEnlargement: true })
      .webp({ quality: 82, effort: 6, smartSubsample: true })
      .toBuffer();
    const hash = createHash("sha1").update(buffer).digest("hex").slice(0, 8);
    const file = `${name}-${width}.${hash}.webp`;
    await writeFile(path.join(OUT, file), buffer);
    variants.push({ width, url: `${PUBLIC_PREFIX}/${file}`, bytes: buffer.length });
  }
  const largest = variants[variants.length - 1];
  manifest[name] = {
    src: largest.url,
    srcSet: variants.map((v) => `${v.url} ${v.width}w`).join(", "),
    width: meta.width,
    height: meta.height,
  };
  console.log(
    name.padEnd(14),
    variants.map((v) => `${v.width}w=${Math.round(v.bytes / 1024)}K`).join("  "),
  );
}

const lcp = manifest[LCP.name];
const html = await readFile(INDEX_HTML, "utf8");
const preload = `    <!-- lcp-preload:start (generated by scripts/resize-images.mjs) -->
    <link
      rel="preload"
      as="image"
      href="${lcp.src}"
      imagesrcset="${lcp.srcSet}"
      imagesizes="${LCP.sizes}"
      type="image/webp"
      fetchpriority="high"
    />
    <!-- lcp-preload:end -->`;
const updated = html.replace(/ {4}<!-- lcp-preload:start[\s\S]*?<!-- lcp-preload:end -->/, preload);
if (updated === html && !html.includes(lcp.src))
  throw new Error("lcp-preload markers missing in index.html");
await writeFile(INDEX_HTML, updated);

const files = await readdir(OUT);
await writeFile(
  MANIFEST,
  `// Generated by scripts/resize-images.mjs — do not edit by hand.
export const IMAGES = ${JSON.stringify(manifest, null, 2)} as const;

export type ImageName = keyof typeof IMAGES;
`,
);
console.log(`\n${files.length} files → ${path.relative(process.cwd(), OUT)}`);
